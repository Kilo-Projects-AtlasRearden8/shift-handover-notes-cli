"""Data models for shift handover notes."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any
import json


@dataclass
class ShiftNote:
    """Represents a single shift note entry."""

    category: str
    bullets: list[str]
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "category": self.category,
            "bullets": self.bullets,
            "timestamp": self.timestamp,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ShiftNote:
        return cls(
            category=data["category"],
            bullets=data["bullets"],
            timestamp=data.get("timestamp", datetime.now().isoformat()),
        )


@dataclass
class ShiftRecord:
    """Represents a complete shift record with multiple note categories."""

    shift_id: str
    unit: str
    date: str
    notes: list[ShiftNote] = field(default_factory=list)
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now().isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "shift_id": self.shift_id,
            "unit": self.unit,
            "date": self.date,
            "notes": [note.to_dict() for note in self.notes],
            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ShiftRecord:
        return cls(
            shift_id=data["shift_id"],
            unit=data["unit"],
            date=data["date"],
            notes=[ShiftNote.from_dict(n) for n in data.get("notes", [])],
            created_at=data.get("created_at", datetime.now().isoformat()),
            updated_at=data.get("updated_at", datetime.now().isoformat()),
        )

    def add_note(self, category: str, bullets: list[str]) -> None:
        """Add a new note category with bullets."""
        self.notes.append(ShiftNote(category=category, bullets=bullets))
        self.updated_at = datetime.now().isoformat()

    def get_notes_by_category(self, category: str) -> list[ShiftNote]:
        """Get all notes for a specific category."""
        return [n for n in self.notes if n.category.lower() == category.lower()]


